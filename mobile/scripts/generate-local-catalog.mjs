/**
 * Reads backend public catalog seed and writes mobile/src/data/generatedLocalCatalog.ts
 * Run from repo root: node mobile/scripts/generate-local-catalog.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const catalogUrl = pathToFileURL(
  join(__dirname, "../../backend/src/db/catalog/publicRecipes.js")
).href;

const { PUBLIC_CATALOG_RECIPES } = await import(catalogUrl);

function slugTitle(title) {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 56);
}

const recipes = PUBLIC_CATALOG_RECIPES.map((row, i) => {
  const id = `local-${slugTitle(row.title) || `recipe-${i + 1}`}`;
  return {
    id,
    title: row.title,
    description: row.description,
    prepTime: row.prep_time,
    cookTime: row.cook_time,
    totalTime: row.total_time,
    servings: row.servings,
    nutrition: row.nutrition,
    dietaryTags: row.dietary_tags ?? [],
    cuisine: row.cuisine,
    difficulty: row.difficulty,
    ingredients: (row.ingredients ?? []).map((ing, j) => ({
      id: `${id}-ing-${j}`,
      name: ing.name,
      quantity: ing.quantity,
      unit: ing.unit,
      ...(ing.notes ? { notes: ing.notes } : {}),
    })),
    steps: (row.steps ?? []).map((s) => ({
      stepNumber: s.stepNumber,
      instruction: s.instruction,
      ...(s.duration != null ? { duration: s.duration } : {}),
      ...(s.timerRequired != null ? { timerRequired: s.timerRequired } : {}),
    })),
  };
});

const header = `/* eslint-disable */
/* Generated by mobile/scripts/generate-local-catalog.mjs — run \`node mobile/scripts/generate-local-catalog.mjs\` after editing backend seed data. */

import type { Recipe } from "@aipron/shared";

`;

const body = `export const LOCAL_CATALOG_RECIPES: Recipe[] = ${JSON.stringify(recipes, null, 2)};
`;

writeFileSync(join(__dirname, "../src/data/generatedLocalCatalog.ts"), header + body);
console.log(`Wrote ${recipes.length} recipes to mobile/src/data/generatedLocalCatalog.ts`);
